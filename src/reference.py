"""Справочный раздел судового журнала яхтсмена — 10 страниц."""

from reportlab.lib.units import mm

# ------------------------------------------------------------ отступы
# Один тип элемента — один отступ. Значения не подгоняются под конкретную
# страницу: если не помещается, режется содержимое, а не интервал.
GAP_TEXT = 5.0 * mm      # после абзаца
GAP_LIST = 6.0 * mm      # после списка
GAP_TABLE = 7.0 * mm     # после таблицы
GAP_FIG = 6.0 * mm       # после схемы, картинки, блока цифр
GAP_NOTE = 6.0 * mm      # после врезки


import figures as F


def build_reference(ctx):
    c = ctx["c"]
    TRIM_W, TRIM_H = ctx["TRIM_W"], ctx["TRIM_H"]
    MT, MB = ctx["MT"], ctx["MB"]
    INK, ACCENT = ctx["INK"], ctx["ACCENT"]
    LABEL, LABEL2 = ctx["LABEL"], ctx["LABEL2"]
    RULE, GRID, FAINT = ctx["RULE"], ctx["GRID"], ctx["FAINT"]
    BODY, BOLD = ctx["BODY"], ctx["BOLD"]
    LBL, LBLB = ctx["LBL"], ctx["LBLB"]
    margins, caps, txt = ctx["margins"], ctx["caps"], ctx["txt"]
    field, bilabel, folio, punch = ctx["field"], ctx["bilabel"], ctx["folio"], ctx["punch"]

    # -------------------------------------------------------------- утилиты
    def head(pno, title, title_en, intro=None):
        ml, mr = margins(pno)
        x, w = ml, TRIM_W - ml - mr
        y = TRIM_H - MT
        caps(c, x, y - 5 * mm, title, 8.4, ACCENT, 1.8)
        txt(c, x + w, y - 5 * mm, title_en, LBL, 6.4, LABEL2, 1.2, "r")
        y -= 9 * mm
        c.setStrokeColor(ACCENT)
        c.setLineWidth(0.8)
        c.line(x, y, x + w, y)
        y -= 7 * mm
        if intro:
            y -= 2.5 * mm
            y -= wrap(x, y, w, intro, 6.9, 10.4, LABEL) + GAP_TEXT
        return x, w, y

    def wrap(x, y, w, text, size=7.1, lead=10.8, color=INK, font=BODY):
        words, line, yy = text.split(), "", y
        for word in words:
            test = (line + " " + word).strip()
            if c.stringWidth(test, font, size) > w and line:
                txt(c, x, yy, line, font, size, color)
                yy -= lead
                line = word
            else:
                line = test
        if line:
            txt(c, x, yy, line, font, size, color)
            yy -= lead
        return y - yy

    def sub(x, w, y, ru, en):
        caps(c, x, y, ru, 6.6, ACCENT, 1.3)
        txt(c, x + w, y, en, LBL, 5.8, LABEL2, 1.0, "r")
        return 6.2 * mm

    def bullets(x, y, w, items, size=6.9, lead=10.6):
        gap = 3.4 * mm
        yy = y
        for it in items:
            c.setFillColor(ACCENT)
            c.circle(x + 0.9 * mm, yy + 1.05 * mm, 0.55 * mm, stroke=0, fill=1)
            h = wrap(x + gap, yy, w - gap, it, size, lead)
            yy -= h + 2.8 * mm
        return y - yy

    def numbered(x, y, w, items, size=6.9, lead=10.6):
        gap = 5.0 * mm
        yy = y
        for i, it in enumerate(items, 1):
            txt(c, x, yy, "%d" % i, LBLB, 7.2, ACCENT, 0)
            h = wrap(x + gap, yy, w - gap, it, size, lead)
            yy -= h + 2.8 * mm
        return y - yy

    def keybox(x, y, w, pairs, ncols=2, row_h=8.4 * mm):
        rows = (len(pairs) + ncols - 1) // ncols
        h = rows * row_h + 3 * mm
        c.setFillColor(FAINT)
        c.rect(x, y - h, w, h, stroke=0, fill=1)
        cw = w / ncols
        for i, (val, cap) in enumerate(pairs):
            r, k = divmod(i, ncols)
            cx = x + k * cw + 3.5 * mm
            cy = y - 3 * mm - r * row_h - 4.8 * mm
            vw = txt(c, cx, cy, val, LBLB, 9.0, ACCENT, 0.2)
            avail = cw - 3.5 * mm - vw - 2 * mm - 3 * mm
            cs, cu = 5.4, cap.upper()
            while cs > 3.9 and c.stringWidth(cu, LBLB, cs) + 0.5 * len(cu) > avail:
                cs -= 0.1
            txt(c, cx + vw + 2 * mm, cy + 0.3 * mm, cu, LBLB, cs, LABEL, 0.5)
        return h

    def table(x, y, w, headers, rows, widths, row_h=7.8 * mm, size=6.7):
        total = sum(widths)
        cw = [w * v / total for v in widths]
        cx = x
        for hd, ww in zip(headers, cw):
            if isinstance(hd, tuple):
                bilabel(c, cx + 1.5 * mm, y - 3.2 * mm, hd[0], hd[1], 5.0, maxw=ww - 3 * mm)
            elif hd:
                caps(c, cx + 1.5 * mm, y - 3.2 * mm, hd, 5.0, LABEL, 0.6)
            cx += ww
        top = y - 5 * mm
        c.setStrokeColor(ACCENT)
        c.setLineWidth(0.6)
        c.line(x, top, x + w, top)
        for r, row in enumerate(rows):
            ry = top - r * row_h
            cx = x
            for j, (val, ww) in enumerate(zip(row, cw)):
                f = LBLB if j == 0 and len(row) > 1 else BODY
                sz = size if f == BODY else size - 0.3
                val = str(val)
                while sz > 5.0 and c.stringWidth(val, f, sz) > ww - 3 * mm:
                    sz -= 0.1
                txt(c, cx + 1.5 * mm, ry - 5.0 * mm, val, f, sz, INK)
                cx += ww
            c.setStrokeColor(RULE)
            c.setLineWidth(0.3)
            c.line(x, ry - row_h, x + w, ry - row_h)
        return y - (top - len(rows) * row_h)

    def blank_rows(x, y, w, headers, widths, n, row_h=8.6 * mm):
        total = sum(widths)
        cw = [w * v / total for v in widths]
        cx = x
        for hd, ww in zip(headers, cw):
            bilabel(c, cx + 1.5 * mm, y - 3.2 * mm, hd[0], hd[1], 5.0, maxw=ww - 3 * mm)
            cx += ww
        top = y - 5 * mm
        c.setStrokeColor(ACCENT); c.setLineWidth(0.6)
        c.line(x, top, x + w, top)
        for r in range(n):
            c.setStrokeColor(RULE); c.setLineWidth(0.35)
            c.line(x, top - (r + 1) * row_h, x + w, top - (r + 1) * row_h)
        cx = x
        c.setStrokeColor(GRID); c.setLineWidth(0.3)
        for ww in cw[:-1]:
            cx += ww
            c.line(cx, top, cx, top - n * row_h)
        return y - (top - n * row_h)

    def caution(x, y, w, text):
        hh = wrap(x + 4 * mm, y - 3.6 * mm, w - 6 * mm, text, 6.8, 10.1, LABEL) + 7 * mm
        c.setStrokeColor(ACCENT); c.setLineWidth(1.4)
        c.line(x + 0.7 * mm, y - hh + 2 * mm, x + 0.7 * mm, y - 1 * mm)
        return hh

    FP = F.palette(ctx)
    img = ctx["img"]
    checkrow = ctx["checkrow"]
    cols = ctx["cols"]

    def fig_blasts(*a, **k):
        return F.fig_blasts(*a, **k)

    def figpage(pno, title, title_en, intro, blocks):
        x, w, y = head(pno, title, title_en, intro)
        for kind, arg in blocks:
            if kind == "fig":
                y -= arg(c, FP, x, y, w) + GAP_FIG
            elif kind == "sub":
                y -= sub(x, w, y, arg[0], arg[1])
            elif kind == "img":
                name, hmm, cap = arg
                y -= img(c, name, x, y, w, hmm * mm) + GAP_FIG
                if cap:
                    y -= F.caption(c, FP, x, y, w, cap) + 4 * mm
            elif kind == "cap":
                y -= F.caption(c, FP, x, y, w, arg) + GAP_TEXT
            elif kind == "bul":
                y -= bullets(x, y, w, arg) + GAP_LIST
            elif kind == "tab":
                y -= table(x, y, w, arg[0], arg[1], arg[2], *arg[3:]) + GAP_TABLE
        return x, w, y

    def finish(pno, geo):
        x, w, y = geo
        if y - MB > 34 * mm:
            caps(c, x, y - 5 * mm, "заметки", 6.0, LABEL2, 1.2)
            yy = y - 13 * mm
            c.setStrokeColor(GRID)
            c.setLineWidth(0.35)
            while yy > MB + 4 * mm:
                c.line(x, yy, x + w, yy)
                yy -= 8.5 * mm
        punch(c, pno)
        folio(c, pno)
        assert y >= MB, "справочная стр. %d переполнена: %.1f мм" % (pno, y / mm)

